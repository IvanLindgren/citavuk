import 'package:flutter/foundation.dart';

/// Повторение слов письмом от руки.
///
/// Проверка здесь — самооценка, а не распознавание. Причина не в лени:
/// открытое распознавание рукописного текста без модели невозможно, а
/// единственная готовая модель (ML Kit Digital Ink) существует только на
/// Android и iOS — ни в браузере, ни на Windows с Linux её нет. Написать
/// «проверку» на сравнении с очертанием шрифта было бы можно, но она отвергала
/// бы нормальный почерк, а ложный отказ в упражнении на память — худшее, что
/// может случиться: человек начинает подгонять почерк под программу вместо
/// того, чтобы вспоминать слово.
///
/// Поэтому карточка спрашивает перевод, человек пишет слово рукой, затем
/// открывает ответ и сам говорит, вспомнил или нет. Расписание повторений при
/// этом общее с обычным режимом — это те же карточки, показанные иначе.

/// Годится ли запись для письма.
///
/// Фразы отсеиваются намеренно: писать рукой предложение долго, а вспоминается
/// оно не так, как слово. Проверка идёт по пробелу — им же отличаются фразы в
/// словаре.
bool writable(String word) {
  final trimmed = word.trim();
  if (trimmed.isEmpty || RegExp(r'\s').hasMatch(trimmed)) return false;
  // Слишком длинное слово не помещается на холст ни на телефоне, ни на
  // мониторе, а перенос строки в письме от руки выглядит как ошибка.
  final length = trimmed.runes.length;
  return length >= 2 && length <= 24;
}

/// Буквы слова для побуквенного режима.
///
/// Делим по кодовым точкам, а не по кодовым единицам UTF-16: сербская
/// диакритика (č, ć, š, ž, đ) в NFC — одна кодовая точка, и обычная подстрока
/// по индексу их не разрубит, а вот суррогатные пары разрубила бы.
List<String> wordLetters(String word) =>
    word.trim().runes.map(String.fromCharCode).toList();


/// Похвала за серию верных ответов подряд в повторении.
///
/// Возвращает текст короткого сообщения на рубежах 5/10/20 и далее каждые
/// 20 — иначе null. Молчание между рубежами осознанно: хвалить за каждую
/// карточку — значит обесценить похвалу и заболтать повторение.
/// Чистая функция, покрыта тестом.
String? streakPraise(int streak) {
  if (streak <= 0) return null;
  switch (streak) {
    case 5:
      return 'Пять подряд без ошибок! Так держать!';
    case 10:
      return 'Десять подряд! Волк довольно виляет хвостом.';
    case 20:
      return 'Двадцать подряд — серьёзная работа!';
    default:
      if (streak > 20 && streak % 20 == 0) {
        return '$streak подряд! Не останавливайся.';
      }
      return null;
  }
}

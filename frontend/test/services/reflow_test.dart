import 'package:flutter_test/flutter_test.dart';
import 'package:srbski_read/services/document_parser.dart';
import 'package:srbski_read/utils/reflow.dart';

/// Разбиение на абзацы обязано совпадать с сайтом до символа: адрес книги при
/// синхронизации считается от списка абзацев, и другое разбиение означает две
/// разные книги на двух устройствах вместо одной.
///
/// Примеры здесь те же, что в web/src/lib/reflow.test.ts.
void main() {
  group('восстановление абзацев', () {
    test('склеивает строки одного абзаца', () {
      expect(
        reflowLines([
          'Вук Караџић је реформисао српски правопис и увео',
          'начело да се пише како се говори, а чита како је',
          'написано.',
        ]),
        [
          'Вук Караџић је реформисао српски правопис и увео начело да се пише '
              'како се говори, а чита како је написано.',
        ],
      );
    });

    test('начинает новый абзац после короткой строки с точкой', () {
      final paragraphs = reflowLines([
        'Први пасус почиње овде и наставља се преко целог реда до краја',
        'реда, а затим се завршава.',
        'Други пасус почиње новом мишљу и такође иде преко целог реда до',
        'самога краја реда.',
      ]);
      expect(paragraphs, hasLength(2));
      expect(paragraphs[0], contains('затим се завршава.'));
      expect(paragraphs[1], startsWith('Други пасус'));
    });

    test('не рвёт абзац на строке, которая дотянулась до края', () {
      expect(
        reflowLines([
          'Прва реченица иде до самога краја реда и ту се завршава тачком.',
          'Друга реченица наставља исти пасус и такође иде до краја реда ту.',
          'Трећа.',
        ]),
        hasLength(1),
      );
    });

    test('склеивает слово, разорванное переносом', () {
      expect(
        reflowLines([
          'Ово је дуга реченица у којој се јавља реч разде-',
          'љена преносом на крају реда, и она мора бити цела.',
        ]).single,
        contains('раздељена'),
      );
    });

    test('тире в конце строки не считает переносом', () {
      expect(
        reflowLines(['Идемо кући —', 'рекао је тихо.']).single,
        'Идемо кући — рекао је тихо.',
      );
    });

    test('пункты списка становятся отдельными абзацами', () {
      expect(
        reflowLines([
          'За решавање теста предвиђено је 120 минута.',
          '• Задатке не мораш да радиш према редоследу.',
          '• Коначне одговоре напиши хемијском оловком.',
        ]),
        [
          'За решавање теста предвиђено је 120 минута.',
          '• Задатке не мораш да радиш према редоследу.',
          '• Коначне одговоре напиши хемијском оловком.',
        ],
      );
    });

    test('нумерованные пункты тоже отделяются', () {
      expect(
        reflowLines([
          'Одговори на следећа питања.',
          '1. Ко је написао Горски вијенац?',
          '2. Које године је објављен?',
        ]),
        hasLength(3),
      );
    });

    test('заголовок из прописных букв стоит отдельно', () {
      expect(
        reflowLines([
          'ТЕСТ ИЗ СРПСКОГ ЈЕЗИКА',
          'Прочитај текст и одговори на питања која следе испод',
          'самога текста.',
        ]),
        [
          'ТЕСТ ИЗ СРПСКОГ ЈЕЗИКА',
          'Прочитај текст и одговори на питања која следе испод самога текста.',
        ],
      );
    });

    test('пустая строка разрывает абзац безусловно', () {
      expect(reflowLines(['Прва', '', 'Друга']), ['Прва', 'Друга']);
    });

    test('пустой ввод даёт пустой результат', () {
      expect(reflowLines([]), isEmpty);
      expect(reflowLines(['', '   ', '']), isEmpty);
    });
  });

  group('документ по страницам', () {
    const head = 'Република Србија МИНИСТАРСТВО ПРОСВЕТЕ';

    test('выбрасывает колонтитулы, повторяющиеся на большинстве страниц', () {
      final paragraphs = reflowDocument([
        [head, 'Први задатак говори о томе како се мери температура ваздуха.'],
        [head, 'Други задатак говори о томе како се мери притисак ваздуха у соби.'],
        [head, 'Трећи задатак говори о томе како се мери влажност ваздуха у соби.'],
        [head, 'Четврти задатак говори о томе како се мери брзина ветра на терену.'],
      ]);
      expect(paragraphs.join('\n'), isNot(contains('МИНИСТАРСТВО')));
      expect(paragraphs, hasLength(4));
    });

    test('не трогает строку, встретившуюся на паре страниц из многих', () {
      final paragraphs = reflowDocument([
        ['Задатак 1. Изрази дати број у облику производа простих чинилаца.'],
        ['Задатак 2. Изрази дати број у облику производа простих чинилаца.'],
        ['Реченица која се среће само овде и нигде више у целом документу.'],
        ['Задатак 4. Изрази дати број у облику производа простих чинилаца.'],
        ['Задатак 5. Изрази дати број у облику производа простих чинилаца.'],
      ]);
      expect(paragraphs.join('\n'), contains('само овде'));
    });

    test('выбрасывает номера страниц', () {
      final paragraphs = reflowDocument([
        ['Текст прве стране који иде до краја реда и ту се завршава тачком.', '1'],
        ['Текст друге стране који иде до краја реда и ту се завршава тачком.', '— 2 —'],
        ['Текст треће стране који иде до краја реда и ту се завршава тачком.', 'стр. 3'],
      ]);
      expect(paragraphs, hasLength(3));
      for (final paragraph in paragraphs) {
        expect(paragraph, isNot(matches(RegExp(r'^\s*\d+\s*$'))));
      }
    });

    test('страницы не склеиваются в один абзац', () {
      expect(
        reflowDocument([
          ['Крај прве стране без тачке на самом крају реда и без икакве'],
          ['Почетак друге стране који наставља другу мисао до краја реда.'],
        ]),
        hasLength(2),
      );
    });

    test('огромный абзац делится по предложениям', () {
      const sentence = 'Ово је реченица која се понавља много пута заредом. ';
      final long = (sentence * 120).trim();
      final paragraphs = reflowDocument([
        [long],
      ]);

      expect(paragraphs.length, greaterThan(1));
      for (final paragraph in paragraphs) {
        expect(paragraph.length, lessThan(2500));
      }
      // Ни одно слово не потеряно и не задвоено.
      expect(paragraphs.join(' '), long);
    });

    test('документ из одной страницы обрабатывается без колонтитулов', () {
      expect(
        reflowDocument([
          ['Једина страна са једном реченицом.'],
        ]),
        ['Једина страна са једном реченицом.'],
      );
    });
  });

  group('склейка строки по глифам', () {
    /// Раскладывает буквы подряд, ставя между словами просвет шириной [gap].
    List<GlyphBox> layout(String text, {double width = 10, double gap = 4}) {
      final boxes = <GlyphBox>[];
      var x = 0.0;
      for (final char in text.split('')) {
        if (char == ' ') {
          x += gap;
          continue;
        }
        boxes.add((text: char, left: x, right: x + width));
        x += width;
      }
      return boxes;
    }

    test('просвет между буквами становится пробелом', () {
      expect(
        DocumentParser.joinGlyphs(layout('предвиђено је 120 минута')),
        'предвиђено је 120 минута',
      );
    });

    test('внутри слова пробел не появляется', () {
      expect(DocumentParser.joinGlyphs(layout('Србија')), 'Србија');
    });

    // Каждая буква приходит отдельным «словом», а пробельные глифы стоят то
    // нулевой ширины, то посреди слова — доверять им нельзя.
    test('пробельные глифы игнорируются', () {
      final boxes = [
        ...layout('sati'),
        (text: ' ', left: 40.0, right: 40.0),
        ...[(text: 'm', left: 40.0, right: 50.0), (text: 'a', left: 50.0, right: 60.0)],
      ];
      expect(DocumentParser.joinGlyphs(boxes), 'satima');
    });

    test('строка, нарисованная поверх себя, не удваивается', () {
      final once = layout('dana');
      expect(DocumentParser.joinGlyphs([...once, ...once]), 'dana');
    });

    test('без координат буквы просто склеиваются', () {
      final boxes = [
        for (final char in 'реч'.split(''))
          (text: char, left: 0.0, right: 0.0),
      ];
      expect(DocumentParser.joinGlyphs(boxes), 'реч');
    });

    test('пустой ввод даёт пустую строку', () {
      expect(DocumentParser.joinGlyphs([]), isEmpty);
      expect(DocumentParser.joinGlyphs([(text: ' ', left: 0, right: 5)]),
          isEmpty);
    });
  });
}

// Package apperr отделяет ошибки, написанные для пользователя, от внутренних.
//
// Обработчики то и дело отдают клиенту err.Error(). Пока ошибка — это «нужен
// sha256 в шестнадцатеричном виде», всё в порядке: текст для того и написан. Но
// по тому же пути наружу уходит и «S3 upload failed: …», и сообщение драйвера
// базы, а это адреса, имена бакетов и структура запросов. Отличить одно от
// другого по типу error нельзя — оба просто error.
//
// Поэтому показывается только то, что помечено явно. Правило «по умолчанию не
// показывать» выбрано намеренно: новая внутренняя ошибка, о которой никто не
// подумал, обязана молчать сама, а не ждать, когда её заметят.
package apperr

import (
	"errors"
	"fmt"
)

// Public — ошибка, чей текст написан для человека и может быть показан.
type Public struct{ err error }

func (p *Public) Error() string { return p.err.Error() }
func (p *Public) Unwrap() error { return p.err }

// User создаёт ошибку, текст которой разрешено показать клиенту.
//
// Пишется по-русски и без подробностей устройства: это сообщение увидит тот,
// кто отправил запрос.
func User(format string, args ...any) error {
	return &Public{err: fmt.Errorf(format, args...)}
}

// Wrap помечает уже существующую ошибку как показываемую.
func Wrap(err error) error {
	if err == nil {
		return nil
	}
	return &Public{err: err}
}

// Message возвращает текст, если ошибку разрешено показать.
//
// Проверка через errors.As, а не сравнением типа: помеченная ошибка может
// оказаться завёрнутой по дороге наверх, и терять пометку из-за этого нельзя.
func Message(err error) (string, bool) {
	var public *Public
	if errors.As(err, &public) {
		return public.Error(), true
	}
	return "", false
}

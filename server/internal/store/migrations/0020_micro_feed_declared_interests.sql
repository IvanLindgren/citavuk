-- Читатель сам говорит, что ему интересно и на каком он уровне.
--
-- Профиль до сих пор строился только по поведению, а поведения при первом
-- заходе нет: новому человеку лента показывала «популярное вперемешку с
-- лёгким» и ждала, пока он налистает сигналов. На чужом языке это дорогая
-- цена — карточка не тридцатисекундный ролик, её читают минуту, и первые
-- десять неподходящих отбивают желание вернуться.
--
-- Названное словами и накопленное поведением живут в разных колонках, потому
-- что refreshMicroFeedProfile ПЕРЕСОБИРАЕТ preferred_tags заново. Положи мы
-- ответы анкеты туда — первое же действие читателя стёрло бы их.
ALTER TABLE micro_feed_profiles_embeddings
    ADD COLUMN IF NOT EXISTS declared_categories text[] NOT NULL DEFAULT '{}';

-- Отдельный признак «анкета пройдена», а не проверка на пустоту списка: пустой
-- список — это осмысленный ответ «показывайте всё подряд», и спрашивать снова
-- значит не услышать сказанное.
ALTER TABLE micro_feed_profiles_embeddings
    ADD COLUMN IF NOT EXISTS onboarded_at timestamptz;

-- Раздел «понравившееся» открывается по актору и листается от свежего.
-- Индекс micro_feed_reactions_actor_idx уже такой, но он не различает лайк и
-- дизлайк — а показывать нужно только лайки.
CREATE INDEX IF NOT EXISTS micro_feed_reactions_liked_idx
    ON micro_feed_reactions (actor_key, updated_at DESC)
    WHERE reaction = 1;

-- Разборы словоформ, которых нет в лексиконе.
--
-- Хранится не ответ модели, а уже проверенный движком разбор: начальная форма,
-- часть речи и признаки, при которых парадигма даёт именно эту форму. Значит,
-- при чтении из кеша перепроверять нечего.
--
-- Как и у толкований, срока жизни нет: разбор слова не портится, а кеш в
-- памяти умирал бы при каждой выкатке — и за ту же «kućicama» провайдеру
-- платилось бы снова.
CREATE TABLE word_form_hints (
    -- Нормализованная словоформа: латиницей, строчными.
    form       text        PRIMARY KEY,
    -- NULL — подсказки нет: либо модель отказалась, либо её догадка не прошла
    -- проверку движком. Отказ кешируется наравне с разбором, иначе выдуманное
    -- слово из опечатки спрашивалось бы у модели при каждом нажатии.
    reading    jsonb,
    model      text        NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now()
);

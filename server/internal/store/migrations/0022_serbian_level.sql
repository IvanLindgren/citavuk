-- Уровень сербского живёт на аккаунте, а не в каждом разделе по отдельности.
--
-- До сих пор уровень спрашивал Вукоток — и хранил его в профиле ленты, у
-- которого ключ не аккаунт, а устройство (actor_key). Поэтому один и тот же
-- человек отвечал на тот же вопрос в браузере, в телефоне и после чистки
-- хранилища, а разделы кроме ленты о его уровне не знали вовсе.
--
-- Колонка на users: уровень — это свойство человека, а не ленты. Пустая строка
-- значит «ещё не спрашивали»: отличать её от A1 обязательно, иначе новичок и
-- неопрошенный сливаются в одно, и спросить второго уже нельзя.
ALTER TABLE users
    ADD COLUMN IF NOT EXISTS serbian_level text NOT NULL DEFAULT '';

-- Откуда взялся уровень: сказал сам («declared») или прошёл тест («test»).
-- Разница нужна не для отчётов: заявленному уровню верить меньше, и когда
-- появится подстройка по чтению, начинать её нужно именно с заявленного.
ALTER TABLE users
    ADD COLUMN IF NOT EXISTS serbian_level_source text NOT NULL DEFAULT '';

ALTER TABLE users
    ADD COLUMN IF NOT EXISTS serbian_level_set_at timestamptz;

-- Проверка на уровне базы, а не только в коде: колонку читают и подбор ленты, и
-- оценка сложности книги, и мусор в ней тихо испортил бы обе.
DO $$
BEGIN
    ALTER TABLE users ADD CONSTRAINT users_serbian_level_check
        CHECK (serbian_level IN ('', 'A1', 'A2', 'B1', 'B2', 'C1'));
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;

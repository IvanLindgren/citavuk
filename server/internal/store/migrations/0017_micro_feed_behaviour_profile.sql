-- Профиль читателя ленты строится по поведению, а не по одним лайкам.
--
-- Прежний профиль собирался исключительно из лайков, и «тёплым» читатель
-- становился после трёх. На практике лайк ставит меньшинство: человек листает,
-- дочитывает то, что зацепило, и пролистывает остальное — не нажимая ничего.
-- Такой читатель оставался «холодным» навсегда, и подбор для него не включался
-- никогда, сколько бы он ни читал.
--
-- Дочитывания и быстрые пролистывания записывались с самого начала
-- (micro_feed_interactions), но в профиль не попадали. Теперь попадают: они и
-- есть плотный сигнал, лайк — редкий.

-- Темы, которые читатель раз за разом пролистывает не читая.
--
-- Отдельная колонка, а не вычисление на лету: подбор идёт на каждый запрос
-- ленты, и считать в нём агрегат по всей истории взаимодействий — верный способ
-- сделать ленту медленной ровно у тех, кто ею пользуется больше всех.
ALTER TABLE micro_feed_profiles_embeddings
    ADD COLUMN IF NOT EXISTS avoided_tags text[] NOT NULL DEFAULT '{}';

-- Перестройка профиля отбирает недавние события одного человека по типу.
-- Прежний индекс (actor_key, created_at DESC, item_id) для этого не годится:
-- по нему приходится читать всю историю читателя и отсеивать событие уже после.
CREATE INDEX IF NOT EXISTS micro_feed_interactions_actor_event_idx
    ON micro_feed_interactions (actor_key, event, created_at DESC);

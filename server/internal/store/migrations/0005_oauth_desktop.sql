-- Возврат после OAuth на настольное приложение.
--
-- У Windows и Linux нет ни deep link, как у Android, ни страницы, на которую
-- можно вернуть браузер, как у сайта. Общепринятое решение — приложение само
-- поднимает HTTP-сервер на 127.0.0.1 со случайным свободным портом и получает
-- ответ туда. Порт заранее неизвестен, поэтому адрес возврата приходит вместе
-- с началом входа и хранится рядом со state.
--
-- Хранить его обязательно на сервере, а не передавать через сам redirect:
-- параметр, пришедший вместе с callback провайдера, подделывается, и тогда
-- одноразовый код входа уехал бы на чужой адрес. Здесь же он привязан к
-- конкретному state, который создан по запросу самого приложения.
--
-- Адрес проверяется при записи (только http на петлевой интерфейс), см.
-- api.parseLoopbackURL. Проверка в базе не дублируется: она бы устарела.
ALTER TABLE oauth_states
    ADD COLUMN return_url text NOT NULL DEFAULT '';

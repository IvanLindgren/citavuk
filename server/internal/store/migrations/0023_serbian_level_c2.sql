-- Шкала уровня на аккаунте доводится до C2.
--
-- Заявка преподавателя (0010) принимает A1…C2, аккаунт принимал A1…C1. Колонки
-- называются одинаково и означают одно и то же — насколько человек знает
-- сербский, — но домены у них разошлись. Пока их ничто не связывает, это не
-- ошибка; но первая же попытка перенести уровень из заявки в аккаунт упёрлась
-- бы в CHECK, и упала бы не при разработке, а у преподавателя с C2.
--
-- Расширение, а не сужение: сужать значило бы чинить рабочие данные (в заявках
-- C2 уже допустим) и отнимать у преподавателей различие, которое им нужно.
--
-- Лента остаётся с A1…C1 намеренно (0014): там уровень стоит не на человеке, а
-- на карточке, и «текст уровня C2» — это не то, что кто-то размечает.
ALTER TABLE users DROP CONSTRAINT IF EXISTS users_serbian_level_check;

ALTER TABLE users ADD CONSTRAINT users_serbian_level_check
    CHECK (serbian_level IN ('', 'A1', 'A2', 'B1', 'B2', 'C1', 'C2'));

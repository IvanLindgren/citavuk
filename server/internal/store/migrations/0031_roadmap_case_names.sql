-- Русские соответствия сербских названий падежей.
--
-- Меняем только отображаемый title. UUID и связанные с ними отметки прогресса
-- остаются прежними, поэтому обновление не сбрасывает уже выполненные темы.

UPDATE roadmap_items
SET title = CASE title
    WHEN 'Номинатив (Номинатив)' THEN 'Номинатив (именительный падеж)'
    WHEN 'Аккузатив (Акузатив) без предлогов' THEN 'Аккузатив (винительный падеж) без предлогов'
    WHEN 'Локатив (Локатив) с предлогами у и на' THEN 'Локатив (предложный падеж) с предлогами у и на'
    WHEN 'Генитив (Генитив) с предлогами из/изван/близу/од' THEN 'Генитив (родительный падеж) с предлогами из/изван/близу/од'
    WHEN 'Датив (Датив)' THEN 'Датив (дательный падеж)'
    WHEN 'Инструментал (Инструментал)' THEN 'Инструментал (творительный падеж)'
    WHEN 'Вокатив (Вокатив)' THEN 'Вокатив (звательный падеж)'
    ELSE title
END,
updated_at = now()
WHERE title IN (
    'Номинатив (Номинатив)',
    'Аккузатив (Акузатив) без предлогов',
    'Локатив (Локатив) с предлогами у и на',
    'Генитив (Генитив) с предлогами из/изван/близу/од',
    'Датив (Датив)',
    'Инструментал (Инструментал)',
    'Вокатив (Вокатив)'
);

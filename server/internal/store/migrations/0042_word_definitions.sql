-- Толкования, сочинённые нейросетью для слов, которых нет в словаре Матицы.
--
-- Кеш в памяти процесса тут не годится: он умирает при каждой выкатке, а за
-- повторное объяснение того же слова провайдер берёт деньги снова. Толкование
-- не портится со временем, поэтому срока жизни у записи нет.
CREATE TABLE word_definitions (
    -- Нормализованное слово: строчными и без пробелов по краям.
    word       text        PRIMARY KEY,
    -- NULL — модель ответила, что такого слова нет. Отказ кешируется наравне
    -- с толкованием: чаще всего это опечатка читателя, и приходит она пачкой.
    entry      jsonb,
    -- Какая модель отвечала: при смене модели видно, что стоит пересобрать.
    model      text        NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now()
);

-- Привязка теста к документу каталога материалов.
--
-- Адреса материала по содержимому (source_sha) для карточки мало: чтобы
-- показать на странице материалов «тест уже составлен», надо знать это ДО
-- скачивания файла, а хеш текста появляется только после разбора. Ключ
-- документа известен сразу, поэтому он и служит вторым адресом.
--
-- Пустая строка означает «тест не из каталога». Такие записи остаются от
-- прежнего раздела с загрузкой своих файлов и в уникальность не входят —
-- иначе второй же тест вне каталога упёрся бы в конфликт.
ALTER TABLE quizzes ADD COLUMN material_key text NOT NULL DEFAULT '';

CREATE UNIQUE INDEX quizzes_material_idx
    ON quizzes (material_key) WHERE material_key <> '';

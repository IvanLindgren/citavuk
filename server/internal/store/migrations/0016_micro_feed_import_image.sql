-- Картинка источника для карточки микро-ленты.
--
-- Поле `image_url` у самой карточки существовало с самого начала, но заполнять
-- его было нечем: разбор источников адрес картинки не доставал вовсе. Лента
-- получалась сплошной стеной текста, и на ленту это походило мало.
--
-- Адрес хранится и у заготовки: генератор превращает заготовку в карточку
-- отдельным шагом и через модель, а модель картинку не видит и передать не
-- может. Без этой колонки адрес терялся бы между выборкой из источника и
-- созданием карточки.
ALTER TABLE micro_feed_imports
    ADD COLUMN IF NOT EXISTS image_url text NOT NULL DEFAULT '';

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const root=join(dirname(fileURLToPath(import.meta.url)),'..');
execFileSync(process.execPath,[join(root,'node_modules/vite/bin/vite.js'),'build','--config','vite.roulette-embed.config.ts'],{cwd:root,stdio:'inherit'});
const script=readFileSync(join(root,'dist-roulette-embed/roulette3d.js'),'utf8');
if(/<\/script/i.test(script))throw new Error('unsafe script end');
const license=readFileSync(join(root,'node_modules/three/LICENSE'),'utf8');
const html=`<!doctype html>\n<!--\n${license}\n-->\n<html lang="ru"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>html,body{margin:0;width:100%;height:100%;overflow:hidden;background:transparent}canvas{display:block;width:100%;height:100%}</style></head><body><canvas></canvas><script>${script}</script></body></html>`;
writeFileSync(join(root,'../frontend/assets/games/roulette3d.html'),html);
console.log(`roulette3d.html: ${(html.length/1024).toFixed(0)} KB`);

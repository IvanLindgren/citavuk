import { describe, expect, it } from 'vitest';

import { reflowDocument, reflowLines } from './reflow';

describe('восстановление абзацев', () => {
  it('склеивает строки одного абзаца', () => {
    expect(
      reflowLines([
        'Вук Караџић је реформисао српски правопис и увео',
        'начело да се пише како се говори, а чита како је',
        'написано.',
      ]),
    ).toEqual([
      'Вук Караџић је реформисао српски правопис и увео начело да се пише како се говори, а чита како је написано.',
    ]);
  });

  it('начинает новый абзац после короткой строки с точкой', () => {
    const paragraphs = reflowLines([
      'Први пасус почиње овде и наставља се преко целог реда до краја',
      'реда, а затим се завршава.',
      'Други пасус почиње новом мишљу и такође иде преко целог реда до',
      'самога краја реда.',
    ]);
    expect(paragraphs).toHaveLength(2);
    expect(paragraphs[0]).toContain('затим се завршава.');
    expect(paragraphs[1]).toMatch(/^Други пасус/);
  });

  it('не рвёт абзац на строке, которая дотянулась до края', () => {
    // Точка в конце полной строки — обычная середина абзаца.
    const paragraphs = reflowLines([
      'Прва реченица иде до самога краја реда и ту се завршава тачком.',
      'Друга реченица наставља исти пасус и такође иде до краја реда ту.',
      'Трећа.',
    ]);
    expect(paragraphs).toHaveLength(1);
  });

  it('склеивает слово, разорванное переносом', () => {
    expect(
      reflowLines([
        'Ово је дуга реченица у којој се јавља реч разде-',
        'љена преносом на крају реда, и она мора бити цела.',
      ]),
    ).toEqual([
      'Ово је дуга реченица у којој се јавља реч разде-љена преносом на крају реда, и она мора бити цела.'.replace(
        'разде-љена',
        'раздељена',
      ),
    ]);
  });

  it('тире в конце строки не считает переносом', () => {
    // Прямая речь: «— рекао је —» переносом не является.
    const [paragraph] = reflowLines([
      'Идемо кући —',
      'рекао је тихо.',
    ]);
    expect(paragraph).toBe('Идемо кући — рекао је тихо.');
  });

  it('пункты списка становятся отдельными абзацами', () => {
    expect(
      reflowLines([
        'За решавање теста предвиђено је 120 минута.',
        '• Задатке не мораш да радиш према редоследу.',
        '• Коначне одговоре напиши хемијском оловком.',
      ]),
    ).toEqual([
      'За решавање теста предвиђено је 120 минута.',
      '• Задатке не мораш да радиш према редоследу.',
      '• Коначне одговоре напиши хемијском оловком.',
    ]);
  });

  it('нумерованные пункты тоже отделяются', () => {
    const paragraphs = reflowLines([
      'Одговори на следећа питања.',
      '1. Ко је написао Горски вијенац?',
      '2. Које године је објављен?',
    ]);
    expect(paragraphs).toHaveLength(3);
  });

  it('заголовок из прописных букв стоит отдельно', () => {
    expect(
      reflowLines([
        'ТЕСТ ИЗ СРПСКОГ ЈЕЗИКА',
        'Прочитај текст и одговори на питања која следе испод',
        'самога текста.',
      ]),
    ).toEqual([
      'ТЕСТ ИЗ СРПСКОГ ЈЕЗИКА',
      'Прочитај текст и одговори на питања која следе испод самога текста.',
    ]);
  });

  it('пустая строка разрывает абзац безусловно', () => {
    expect(reflowLines(['Прва', '', 'Друга'])).toEqual(['Прва', 'Друга']);
  });

  it('пустой ввод даёт пустой результат', () => {
    expect(reflowLines([])).toEqual([]);
    expect(reflowLines(['', '   ', ''])).toEqual([]);
  });
});

describe('документ по страницам', () => {
  /** Колонтитул экзаменационного теста — на каждой странице один и тот же. */
  const HEAD = 'Република Србија МИНИСТАРСТВО ПРОСВЕТЕ';

  it('выбрасывает колонтитулы, повторяющиеся на большинстве страниц', () => {
    const pages = [
      [HEAD, 'Први задатак говори о томе како се мери температура ваздуха.'],
      [HEAD, 'Други задатак говори о томе како се мери притисак ваздуха у соби.'],
      [HEAD, 'Трећи задатак говори о томе како се мери влажност ваздуха у соби.'],
      [HEAD, 'Четврти задатак говори о томе како се мери брзина ветра на терену.'],
    ];
    const paragraphs = reflowDocument(pages);
    expect(paragraphs.join('\n')).not.toContain('МИНИСТАРСТВО');
    expect(paragraphs).toHaveLength(4);
  });

  it('не трогает строку, встретившуюся на паре страниц из многих', () => {
    const pages = [
      ['Задатак 1. Изрази дати број у облику производа простих чинилаца.'],
      ['Задатак 2. Изрази дати број у облику производа простих чинилаца.'],
      ['Реченица која се среће само овде и нигде више у целом документу.'],
      ['Задатак 4. Изрази дати број у облику производа простих чинилаца.'],
      ['Задатак 5. Изрази дати број у облику производа простих чинилаца.'],
    ];
    expect(reflowDocument(pages).join('\n')).toContain('само овде');
  });

  it('выбрасывает номера страниц', () => {
    const pages = [
      ['Текст прве стране који иде до краја реда и ту се завршава тачком.', '1'],
      ['Текст друге стране који иде до краја реда и ту се завршава тачком.', '— 2 —'],
      ['Текст треће стране који иде до краја реда и ту се завршава тачком.', 'стр. 3'],
    ];
    const paragraphs = reflowDocument(pages);
    expect(paragraphs).toHaveLength(3);
    for (const paragraph of paragraphs) {
      expect(paragraph).not.toMatch(/^\s*\d+\s*$/);
    }
  });

  it('страницы не склеиваются в один абзац', () => {
    const pages = [
      ['Крај прве стране без тачке на самом крају реда и без икакве'],
      ['Почетак друге стране који наставља другу мисао до краја реда.'],
    ];
    expect(reflowDocument(pages)).toHaveLength(2);
  });

  it('огромный абзац делится по предложениям', () => {
    const sentence = 'Ово је реченица која се понавља много пута заредом. ';
    const pages = [[sentence.repeat(120).trim()]];
    const paragraphs = reflowDocument(pages);

    expect(paragraphs.length).toBeGreaterThan(1);
    for (const paragraph of paragraphs) {
      expect(paragraph.length).toBeLessThan(2500);
    }
    // Ни одно слово не потеряно и не задвоено.
    expect(paragraphs.join(' ').replace(/\s+/g, ' ')).toBe(
      sentence.repeat(120).trim().replace(/\s+/g, ' '),
    );
  });

  it('документ из одной страницы обрабатывается без колонтитулов', () => {
    expect(reflowDocument([['Једина страна са једном реченицом.']])).toEqual([
      'Једина страна са једном реченицом.',
    ]);
  });
});

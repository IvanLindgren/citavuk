/**
 * Что в ответе не считается ошибкой.
 *
 * Проверка раньше срезала только точку в конце, поэтому пропущенная запятая
 * внутри фразы отменяла верный перевод целиком. Это неправильно: упражнения
 * Читавука проверяют слова, формы и порядок слов, а расстановка запятых —
 * отдельное умение, которому здесь никто не учит и за которое здесь нельзя
 * наказывать. Тем более что в переводе запятая часто ставится по выбору
 * пишущего, а «эталон» в задании один.
 *
 * Правило одно на все упражнения: уроки, дорожная карта и курс зовут отсюда,
 * чтобы «принято» значило одно и то же везде.
 */

/** Знаки, которых в сравнении просто нет. */
const MARKS = /[.,!?;:…"«»„“”]+/gu;

/**
 * Тире между словами. Дефис внутри слова не трогается: «из-за» и «изза» —
 * разные написания, а «то — то» и «то то» отличаются только вкусом.
 */
const DASHES = /(^|\s)[-–—]+(?=\s|$)/gu;

const SPACES = /\s+/gu;

/**
 * Снимает пунктуацию, не трогая сами слова.
 *
 * Знак заменяется пробелом, а не удаляется: без пробела после запятой
 * «да,нет» иначе склеилось бы в «данет» и перестало совпадать с «да нет» —
 * то есть строгость к запятой сменилась бы на строгость к пробелу.
 */
export function stripAnswerPunctuation(value: string): string {
  return value.replace(MARKS, ' ').replace(DASHES, '$1').replace(SPACES, ' ').trim();
}

/**
 * Приведение ответа к сравнимому виду для уроков и дорожной карты.
 *
 * Регистр по сербской локали: в ней свои пары вроде Đ/đ.
 */
export function normalizeAnswer(value: string): string {
  return stripAnswerPunctuation(value).toLocaleLowerCase('sr');
}

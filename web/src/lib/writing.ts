/**
 * Повторение слов письмом от руки.
 *
 * Проверка здесь — самооценка, а не распознавание. Причина не в лени: открытое
 * распознавание рукописного текста без модели невозможно, а единственная
 * доступная готовая модель (ML Kit Digital Ink) есть только на Android и iOS —
 * ни в браузере, ни на Windows с Linux её нет. Написать «проверку» на
 * сравнении с очертанием шрифта было бы можно, но она отвергала бы нормальный
 * почерк, а ложный отказ в упражнении на память — худшее, что может случиться:
 * человек начинает подгонять почерк под программу вместо того, чтобы вспоминать
 * слово.
 *
 * Поэтому карточка спрашивает перевод, человек пишет слово рукой, затем
 * открывает ответ и сам говорит, вспомнил или нет. Расписание повторений при
 * этом общее с обычным режимом — это те же карточки, показанные иначе.
 */

/**
 * Годится ли запись для письма.
 *
 * Фразы отсеиваются намеренно: писать рукой предложение долго, а вспоминается
 * оно не так, как слово. Проверка идёт по пробелу — им же отличаются фразы в
 * словаре.
 */
export function writable(word: string): boolean {
  const trimmed = word.trim();
  if (!trimmed || /\s/.test(trimmed)) return false;
  // Слишком длинное слово не помещается на холст ни на телефоне, ни на
  // мониторе, а перенос строки в письме от руки выглядит как ошибка.
  const letters = [...trimmed].length;
  return letters >= 2 && letters <= 24;
}

/**
 * Буквы слова для побуквенного режима.
 *
 * Диакритика в сербской латинице — часть буквы, а не отдельный знак, поэтому
 * разбивать надо по видимым символам, а не по кодовым единицам: иначе «č»
 * распалось бы на две «буквы», из которых вторая невидима.
 */
export function letters(word: string): string[] {
  return [...word.trim().normalize('NFC')];
}
